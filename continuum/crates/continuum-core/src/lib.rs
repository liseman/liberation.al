/// A payload or producer id: a 128-bit UUIDv7, kept as its 16 bytes in RFC 9562 (big-endian) order, so ids sort by
/// creation time. These are the same ids v1's `domain/kernel.py` uses (it stores them as strings).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Uuid(pub [u8; 16]);

impl Uuid {
    /// Milliseconds since the Unix epoch from a UUIDv7's first 48 bits.
    #[must_use]
    pub fn unix_ms(self) -> u64 {
        let b = self.0;
        u64::from_be_bytes([0, 0, b[0], b[1], b[2], b[3], b[4], b[5]])
    }
}

impl From<Uuid> for schema::continuum::Uuid {
    fn from(id: Uuid) -> Self {
        Self::new(&id.0)
    }
}

impl From<&schema::continuum::Uuid> for Uuid {
    fn from(id: &schema::continuum::Uuid) -> Self {
        Self(id.bytes().into())
    }
}

impl fmt::Display for Uuid {
    /// The hyphenated lowercase form, as `str(uuid.UUID(...))` prints it in Python.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for (i, byte) in self.0.iter().enumerate() {
            if matches!(i, 4 | 6 | 8 | 10) {
                f.write_str("-")?;
            }
            write!(f, "{byte:02x}")?;
        }
        Ok(())
    }
}

/// A slot in a shared memory slab: its size class, its index in that class, and its generation.
///
/// The generation changes every time the slot is freed, so a handle to a recycled slot is detected as stale instead
/// of reading someone else's bytes (the ABA problem).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct SlotHandle {
    /// The size class.
    pub class: u16,
    /// The slot's index within its class.
    pub index: u32,
    /// The slot's generation when the handle was made.
    pub generation: u32,
}

impl SlotHandle {
    /// Size of the wire form from [`SlotHandle::to_le_bytes`].
    pub const ENCODED_LEN: usize = 12;

    /// Little-endian wire form: class (u16), two reserved zero bytes, index (u32), generation (u32).
    #[must_use]
    pub fn to_le_bytes(self) -> [u8; Self::ENCODED_LEN] {
        let mut out = [0u8; Self::ENCODED_LEN];
        out[0..2].copy_from_slice(&self.class.to_le_bytes());
        out[4..8].copy_from_slice(&self.index.to_le_bytes());
        out[8..12].copy_from_slice(&self.generation.to_le_bytes());
        out
    }

    /// Reads the form [`SlotHandle::to_le_bytes`] writes.
    #[must_use]
    pub fn from_le_bytes(b: [u8; Self::ENCODED_LEN]) -> Self {
        Self {
            class: u16::from_le_bytes([b[0], b[1]]),
            index: u32::from_le_bytes([b[4], b[5], b[6], b[7]]),
            generation: u32::from_le_bytes([b[8], b[9], b[10], b[11]]),
        }
    }
}

/// The bytes a USB camera's frame is planned at: the size of the Tier 0 slot the broker reserves for it and capture
/// claims, so both pick the same slot class. Raw frames (UYVY, and everything AVFoundation delivers) are
/// 4:2:2 rows padded to 64 bytes; MJPEG's is a conservative bound, an uncompressed 4:2:2 frame plus 64 KiB of
/// headers. `None` for a zero size or an overflow.
#[must_use]
pub fn camera_frame_bound(width: u32, height: u32, raw: bool) -> Option<u64> {
    if width == 0 || height == 0 {
        return None;
    }
    let row = u64::from(width).checked_mul(2)?;
    if raw {
        row.checked_next_multiple_of(64)?.checked_mul(u64::from(height))
    } else {
        row.checked_mul(u64::from(height))?.checked_add(64 << 10)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn page_align_is_16k() {
        assert_eq!(PAGE_ALIGN, 16_384);
    }

    #[test]
    fn align_up_16k_rounds_to_the_next_page() {
        assert_eq!(align_up_16k(0), 0);
        assert_eq!(align_up_16k(1), 16_384);
        assert_eq!(align_up_16k(4096), 16_384);
        assert_eq!(align_up_16k(PAGE_ALIGN), PAGE_ALIGN);
        assert_eq!(align_up_16k(PAGE_ALIGN + 1), 2 * PAGE_ALIGN);
        assert_eq!(checked_align_up_16k(usize::MAX), None);
    }

    #[test]
    fn a_4k_offset_is_not_16k_aligned() {
        assert!(!is_aligned_16k(4096));
        assert!(is_aligned_16k(0));
        assert!(is_aligned_16k(3 * PAGE_ALIGN));
    }

    #[test]
    fn align_up_16k_matches_division_for_many_sizes() {
        for n in (0..10 * PAGE_ALIGN).step_by(997) {
            let got = align_up_16k(n);
            assert!(is_aligned_16k(got));
            assert!(got >= n && got - n < PAGE_ALIGN);
            assert_eq!(got, n.div_ceil(PAGE_ALIGN) * PAGE_ALIGN);
        }
    }

    #[test]
    fn slot_handle_round_trips() {
        let h = SlotHandle { class: 7, index: 0xdead_beef, generation: u32::MAX };
        assert_eq!(SlotHandle::from_le_bytes(h.to_le_bytes()), h);
    }

    #[test]
    fn a_payload_header_round_trips_through_the_schema() {
        use schema::continuum::{
            CaptureInfo, CaptureInfoArgs, PayloadHeader, PayloadHeaderArgs, finish_payload_header_buffer,
            root_as_payload_header,
        };
        let id = Uuid([7; 16]);
        let parent = Uuid([1; 16]);
        let mut b = flatbuffers::FlatBufferBuilder::new();
        let shape = b.create_string("NV12");
        let parents = b.create_vector(&[schema::continuum::Uuid::from(parent)]);
        let capture = CaptureInfo::create(
            &mut b,
            &CaptureInfoArgs { width: 3840, height: 2160, stride: 3840, flip: true, ..Default::default() },
        );
        let header = PayloadHeader::create(
            &mut b,
            &PayloadHeaderArgs {
                id: Some(&id.into()),
                stream_id: 3,
                start_ns: 1_761_700_000_000_000_000,
                end_ns: 1_761_700_000_016_666_667,
                layer: DomainLayer::Layer1Raw,
                format: PayloadFormat::RawBytes,
                shape_name: Some(shape),
                parents: Some(parents),
                source_tier: StorageTier::Tier0Hot,
                capture: Some(capture),
                ..Default::default()
            },
        );
        finish_payload_header_buffer(&mut b, header);

        let h = root_as_payload_header(b.finished_data()).unwrap();
        assert_eq!(Uuid::from(h.id().unwrap()), id);
        assert_eq!((h.stream_id(), h.end_ns() - h.start_ns()), (3, 16_666_667));
        assert_eq!(h.shape_name(), Some("NV12"));
        assert_eq!(Uuid::from(h.parents().unwrap().get(0)), parent);
        let c = h.capture().unwrap();
        assert_eq!((c.width(), c.height(), c.flip()), (3840, 2160, true));
        assert_eq!(h.confidence(), None, "an unset optional stays absent, not 0.0");
        assert!(h.compute().is_none() && h.producer().is_none());
    }

    #[test]
    fn uuid_prints_like_python_and_reads_its_timestamp() {
        // uuid.UUID("01890a5d-ac96-774b-bcce-b302099a8057"), a UUIDv7 made at 1686977981590 ms.
        let id = Uuid([0x01, 0x89, 0x0a, 0x5d, 0xac, 0x96, 0x77, 0x4b, 0xbc, 0xce, 0xb3, 0x02, 0x09, 0x9a, 0x80, 0x57]);
        assert_eq!(id.to_string(), "01890a5d-ac96-774b-bcce-b302099a8057");
        assert_eq!(id.unix_ms(), 0x0189_0a5d_ac96);
    }
}
