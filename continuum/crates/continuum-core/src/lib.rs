/// The control protocol's major version (schemas/continuum.fbs). The broker refuses a `Hello` whose major differs;
/// bump it for a change that isn't backward compatible. Minor versions only add fields and messages at the end, so
/// any minor works with any other. Major 1 removed the copy-group and `RetireCopy` messages.
pub const SCHEMA_MAJOR: u16 = 1;
/// The control protocol's minor version; see [`SCHEMA_MAJOR`].
pub const SCHEMA_MINOR: u16 = 35;

/// The alignment of every slab, ring segment, and mmap offset, in bytes (the Apple Silicon page size).
pub const PAGE_ALIGN: usize = 16 * 1024;

/// Rounds `size` up to the next multiple of [`PAGE_ALIGN`]. Panics on overflow; see [`checked_align_up_16k`].
#[must_use]
pub const fn align_up_16k(size: usize) -> usize {
    match checked_align_up_16k(size) {
        Some(v) => v,
        None => panic!("align_up_16k overflowed"),
    }
}

/// Rounds `size` up to the next multiple of [`PAGE_ALIGN`], or `None` on overflow.
#[must_use]
pub const fn checked_align_up_16k(size: usize) -> Option<usize> {
    match size.checked_add(PAGE_ALIGN - 1) {
        Some(v) => Some(v & !(PAGE_ALIGN - 1)),
        None => None,
    }
}

/// Whether `offset` is a multiple of [`PAGE_ALIGN`].
#[must_use]
pub const fn is_aligned_16k(offset: usize) -> bool {
    offset.is_multiple_of(PAGE_ALIGN)
}

