//! Shared types for Continuum Broker: the 16 KB alignment constant and helpers, ids, the schema, and the owned types
//! the catalog, scheduler, and broker pass each other (headers, locators, intervals, stage and boot ids).
//!
//! The schema's types (from `schemas/continuum.fbs`) are in [`schema`]; its enums and [`ClockAnchor`] are
//! re-exported here. Times are `u64` UTC nanoseconds since the Unix epoch everywhere (docs/CONTINUUM.md, decision 9).
//!
//! Every slab slot and ring segment in shared memory starts on a [`PAGE_ALIGN`] boundary. 16 KB is the page size on
//! Apple Silicon (the deploy target), and a multiple of the 4 KB page on x86 Linux, so one layout works on both and
//! a mapped slot can be handed to Metal (no-copy buffers) or CUDA (`cudaHostRegister`) as is. Never hardcode 4096.

