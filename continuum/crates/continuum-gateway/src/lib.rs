//! Continuum's browser gateway (docs/CONTINUUM.md, "Browser gateway" and decision 12): a broker client of its own
//! that serves the dashboard over WebSockets (the default) and WebTransport (opt-in, with a certificate), sending
//! video as encoded access units or JPEG frames that the browser decodes with WebCodecs, and overlays that the
//! browser draws over the frame with the same capture time. There is no WebRTC.
//!
//! Every binary message starts with the 16 byte [`header::FrameHeader`]. The client steers a session with small JSON
//! messages ([`control`]): list the streams, send the frames of a time range, or follow a stream live. Recorded
//! ranges come straight from the tier worker's chunk files ([`source`]) until the broker's `Query` is wired; live
//! streams need the broker's subscriptions and are refused until then.
//!
//! The two transports carry the same messages: over WebSockets a control message is a text frame and a video or
//! overlay message is a binary frame; over WebTransport ([`wt`]) control messages go on the client's bidirectional
//! stream, each prefixed by its length, and every binary message is its own server-opened unidirectional stream.

