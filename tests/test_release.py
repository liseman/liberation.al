"""The release tool gives each platform the pins that apply to it with their hashes, and refuses a tag or a set of
notes that would make a wrong release."""

import importlib.util
import re
import sys
from pathlib import Path
from types import ModuleType

import pytest


def _load() -> ModuleType:
    path = Path(__file__).resolve().parent.parent / "tools" / "release.py"
    spec = importlib.util.spec_from_file_location("release_tool", path)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["release_tool"] = module
    spec.loader.exec_module(module)
    return module


release = _load()

# What `uv export` writes: a header, pins with markers, hashes on continuation lines, and "via" comments.
EXPORTED = """# This file was autogenerated by uv via the following command:
#    uv export --frozen --all-extras
accelerate==1.12.0 ; platform_machine == 'x86_64' and sys_platform == 'linux' \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via qwen-tts-hf
mlx==0.31.0 ; platform_machine == 'arm64' and sys_platform == 'darwin' \\
    --hash=sha256:cccc
numpy==2.4.1 \\
    --hash=sha256:dddd \\
    --hash=sha256:eeee
    # via
    #   accelerate
    #   mlx
sounddevice==0.5.5 ; sys_platform == 'linux' \\
    --hash=sha256:ffff
"""


def test_the_package_constraints_keep_every_platforms_pins_and_markers_without_hashes() -> None:
    assert release.constraints(EXPORTED) == (
        "accelerate==1.12.0 ; platform_machine == 'x86_64' and sys_platform == 'linux'\n"
        "mlx==0.31.0 ; platform_machine == 'arm64' and sys_platform == 'darwin'\n"
        "numpy==2.4.1\n"
        "sounddevice==0.5.5 ; sys_platform == 'linux'\n"
    )


@pytest.mark.parametrize(
    ("platform", "names"),
    [
        ("linux-x86_64", ["accelerate", "numpy", "sounddevice"]),
        ("linux-aarch64", ["numpy", "sounddevice"]),
        ("macos-arm64", ["mlx", "numpy"]),
    ],
)
def test_a_platform_lock_has_only_the_pins_whose_markers_hold_there(platform: str, names: list[str]) -> None:
    locked = release.lock(EXPORTED, platform)
    assert re.findall(r"^(\S+)==", locked, flags=re.MULTILINE) == names


def test_a_platform_lock_keeps_each_pins_hashes_and_drops_the_marker_it_answered() -> None:
    assert release.lock(EXPORTED, "linux-aarch64") == (
        "numpy==2.4.1 \\\n    --hash=sha256:dddd \\\n    --hash=sha256:eeee\nsounddevice==0.5.5 \\\n    --hash=sha256:ffff\n"
    )


def test_a_pin_without_hashes_is_refused_in_a_lock() -> None:
    with pytest.raises(ValueError, match=r"numpy==2\.4\.1 has no hashes"):
        release.lock("numpy==2.4.1\n", "linux-x86_64")


def test_a_line_that_is_not_a_pin_is_refused() -> None:
    with pytest.raises(ValueError, match="not a pinned package"):
        release.pins("./continuum\n")


PYPROJECT = '[project]\nname = "liberational-pack"\nversion = "0.2.0"\n'


def test_a_tag_names_the_version_the_project_declares() -> None:
    assert release.version("v0.2.0", PYPROJECT) == "0.2.0"


@pytest.mark.parametrize(
    ("tag", "why"),
    [
        pytest.param("v0.3.0", "pyproject.toml says 0.2.0", id="another-version"),
        pytest.param("0.2.0", "isn't a release tag", id="no-v"),
        pytest.param("v0.2", "isn't a release tag", id="two-parts"),
        pytest.param("v0.2.0-fix", "isn't a release tag", id="suffix"),
    ],
)
def test_a_tag_that_does_not_match_the_project_is_refused(tag: str, why: str) -> None:
    with pytest.raises(ValueError, match=re.escape(why)):
        release.version(tag, PYPROJECT)


def test_a_prerelease_tag_matches_a_prerelease_version() -> None:
    assert release.version("v0.2.0rc1", PYPROJECT.replace("0.2.0", "0.2.0rc1")) == "0.2.0rc1"


RELEASES = """# Releases

How releases are made.

## 0.2.0

The supervisor runs the scheduled jobs.

An upgrade resets the vector index, which is rebuilt at the next start.

## 0.1.0

The first release. An upgrade resets nothing.

## 0.0.9

Internal.
"""


def test_the_notes_are_the_versions_own_section() -> None:
    assert release.notes("0.2.0", RELEASES) == (
        "The supervisor runs the scheduled jobs.\n\n"
        "An upgrade resets the vector index, which is rebuilt at the next start.\n"
    )


def test_the_last_sections_notes_end_at_the_file() -> None:
    assert release.notes("0.1.0", RELEASES) == "The first release. An upgrade resets nothing.\n"


def test_a_version_with_no_section_is_refused() -> None:
    with pytest.raises(ValueError, match=re.escape("no section for 0.3.0")):
        release.notes("0.3.0", RELEASES)


def test_notes_that_do_not_say_what_an_upgrade_resets_are_refused() -> None:
    with pytest.raises(ValueError, match=r"0\.0\.9 don't say what an upgrade resets"):
        release.notes("0.0.9", RELEASES)


def test_notes_rewrites_relative_link_up_a_level() -> None:
    sample = "## 0.2.0\n\nSee [MIGRATING.md](../MIGRATING.md) for upgrade notes.\n\nAn upgrade resets nothing.\n"
    result = release.notes("0.2.0", sample, repo="https://github.com/liseman/liberation.al")
    assert "[MIGRATING.md](https://github.com/liseman/liberation.al/blob/v0.2.0/MIGRATING.md)" in result


def test_notes_rewrites_sibling_page_with_an_anchor() -> None:
    sample = "## 0.2.0\n\nRead [running instructions](RUNNING.md#start) first.\n\nAn upgrade resets nothing.\n"
    result = release.notes("0.2.0", sample, repo="https://github.com/liseman/liberation.al")
    assert (
        "[running instructions](https://github.com/liseman/liberation.al/blob/v0.2.0/docs/RUNNING.md#start)" in result
    )


def test_notes_rewrites_same_file_anchor() -> None:
    sample = "## 0.2.0\n\nReview [Notes](#notes) for details.\n\nAn upgrade resets nothing.\n"
    result = release.notes("0.2.0", sample, repo="https://github.com/liseman/liberation.al")
    assert "[Notes](https://github.com/liseman/liberation.al/blob/v0.2.0/docs/RELEASES.md#notes)" in result


def test_notes_leaves_absolute_links_untouched() -> None:
    sample = (
        "## 0.2.0\n\n"
        "Installed via [uv](https://docs.astral.sh/uv/) or email [team](mailto:team@example.com).\n\n"
        "An upgrade resets nothing.\n"
    )
    result = release.notes("0.2.0", sample, repo="https://github.com/liseman/liberation.al")
    assert "[uv](https://docs.astral.sh/uv/)" in result
    assert "[team](mailto:team@example.com)" in result


def test_notes_leaves_links_inside_code_blocks_untouched() -> None:
    sample = (
        "## 0.2.0\n\nExample block:\n\n```sh\n[in code block](../MIGRATING.md)\n```\n\nAn upgrade resets nothing.\n"
    )
    result = release.notes("0.2.0", sample, repo="https://github.com/liseman/liberation.al")
    assert "[in code block](../MIGRATING.md)" in result


def test_apt_release_notes_commands_match_releases_documentation() -> None:
    root = Path(__file__).resolve().parent.parent
    releases_text = (root / "docs" / "RELEASES.md").read_text()
    apt_notes_text = (root / "packaging" / "apt-release-notes.md").read_text()

    apt_blocks = re.findall(r"```sh\n(.*?)\n```", apt_notes_text, flags=re.DOTALL)
    assert len(apt_blocks) >= 2, "apt-release-notes.md must contain install and upgrade code blocks"
    apt_install, apt_upgrade = apt_blocks[0].strip(), apt_blocks[1].strip()

    install_section = releases_text.split("## Install with apt")[1].split("##")[0]
    install_doc = re.search(r"```sh\n(.*?)\n```", install_section, flags=re.DOTALL)
    assert install_doc is not None
    assert apt_install == install_doc.group(1).strip()

    upgrade_section = releases_text.split("### Upgrade, remove, or purge an apt install")[1].split("###")[0]
    upgrade_doc = re.search(r"```sh\n(.*?)\n```", upgrade_section, flags=re.DOTALL)
    assert upgrade_doc is not None
    assert apt_upgrade == upgrade_doc.group(1).strip()
